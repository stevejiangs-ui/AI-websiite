export function expertOf(id) {
  return EXPERTS.find((e) => e.id === id) || null;
}

/** 某个页面该用哪位专家（页面 → 专家 id 列表） */
export function expertsForPage(view) {
  return EXPERTS.filter((e) => e.pages.includes(view));
}
